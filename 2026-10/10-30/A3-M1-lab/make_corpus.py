"""쇼핑몰 고객 문의 말뭉치(가상)를 만든다. 같은 seed면 항상 같은 파일."""
import random
random.seed(42)
items = ["냉장고", "세탁기", "에어컨", "소파", "운동화", "티셔츠", "노트북", "무선이어폰", "전기밥솥", "캠핑의자",
         "책상", "모니터", "청소기", "가습기", "커피머신", "블루투스스피커", "유모차", "러닝화", "패딩", "선풍기"]
codes = ["AB-1200", "RF85T", "WM-9000X", "SM-S921N", "KQ55", "LG-27UP"]
units = ["35kg", "2.5m", "120cm", "500ml", "3.5L", "15인치", "27인치", "1.2kg", "40mm"]
qs = [
    "{i} 배송은 언제 오나요?", "{i} 배송비는 얼마인가요?", "{i} 주문을 취소하고 싶어요", "{i} 교환이 가능한가요?",
    "{i} 반품하려면 어떻게 하나요?", "{i} 환불은 언제 되나요?", "{i} 상품이 파손되어 도착했어요", "{i} 색상을 바꾸고 싶어요",
    "{c} 모델 {i} 재고 있나요?", "{u} {i}도 무료 배송인가요?", "{i} 설치 기사님 방문 일정은요?", "{i} 사이즈 교환 되나요?",
    "택배로 받은 {i}에서 소리가 나요", "{i} 무이자 할부 가능한가요?", "{i} 적립금 사용할 수 있나요?", "{i} 쿠폰 적용이 안 돼요",
    "{i} 언제 도착해요?", "{i} 배송지 변경하고 싶어요", "{i} 영수증 발급해 주세요", "{i} AS 기간은 얼마나 되나요?",
]
answers = ["주문 후 평일 기준 2~3일 이내에 도착합니다.", "3만 원 이상 구매 시 무료 배송입니다.", "출고 전에는 마이페이지에서 바로 취소할 수 있습니다.",
           "상품을 받은 날부터 7일 이내에 신청할 수 있습니다.", "카드 결제는 3영업일 이내에 환불됩니다.", "대형 가전은 설치 기사가 직접 방문합니다.",
           "제주·도서산간은 3~5일 걸립니다.", "free shipping 이벤트는 매월 1일에 시작합니다.", "적립금은 1,000원 단위로 사용할 수 있습니다."]
lines = []
for _ in range(1500):
    t = random.choice(qs)
    lines.append(t.format(i=random.choice(items), c=random.choice(codes), u=random.choice(units)))
for _ in range(500):
    lines.append(random.choice(answers))
open("shop_corpus.txt", "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(len(lines), "줄 저장: shop_corpus.txt")
